export function resolveLocale(value: string | null | undefined): Locale {
  return value?.toLowerCase().split(/[-_]/)[0] === "de" ? "de" : "en";
}

export function translate(locale: Locale, key: string, params: Record<string, string | number> = {}): string {
  const message = locale === "en" && Object.hasOwn(ENGLISH, key) ? ENGLISH[key]! : key;
  return message.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(params, name) ? String(params[name]) : match);
}
